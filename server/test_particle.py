# -*- coding: utf-8 -*-
"""助詞の読み替え（read_particles）の単体試験。本体も通信も要らない。

公式歌詞 25 曲に出てくる「は」「へ」を全部書き出して、1 件ずつ人手で
正解を決めたもの（2026-08-23）。規則で当てにいくと必ずどちらかを外す:
  ・「しょうりへみちびけ」は空白が無いので語末に見えない（→ 取りこぼす）
  ・「みせつけろへらる」の へ は ヘラルド の一部（→ 取り違える）
最後の 2 件は対照（歌詞には無いが、規則の当たり外れが分かるもの）。

  ./.venv/bin/python test_particle.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import sheet_song

CASES = [
    # (歌詞, 歌うときの読み)
    ("しょうりへみちびけ", "しょうりえみちびけ"),                    # 林琢真
    ("うてよしょうりへのいちだ", "うてよしょうりえのいちだ"),          # 松尾汐恩
    ("さあうてとばせしょうりへの とびらをひらけ",
     "さあうてとばせしょうりえの とびらをひらけ"),                    # 戸柱恭孝
    ("かちへのおもいこめ", "かちえのおもいこめ"),                     # 石上泰輝
    ("つきすすめしょうりへのみち", "つきすすめしょうりえのみち"),      # 梶原昂希
    ("うてとわのほしへ", "うてとわのほしえ"),                         # 蝦名達夫
    ("みせつけろへらる", "みせつけろへらる"),                         # ヘラルド（名前）
    ("ねらいははずさない", "ねらいわはずさない"),                     # 先発左腕のテーマ
    ("ほこらしきひとふりは", "ほこらしきひとふりわ"),                 # 三森大貴
    ("たくみな グラブさばきは", "たくみな グラブさばきわ"),           # 柴田竜拓
    ("はしりだす そのさきには", "はしりだす そのさきにわ"),           # 関根大気
    ("みなとおとこはだれも みんな", "みなとおとこわだれも みんな"),   # 代打のテーマ
    ("つよくはやくかぜのように", "つよくはやくかぜのように"),         # はやく
    ("はしりぬけたくま", "はしりぬけたくま"),                         # はしり
    ("ゆめはこぶ", "ゆめはこぶ"),                                     # はこぶ
    ("さあ はしりだせ はまかぜせにうけ", "さあ はしりだせ はまかぜせにうけ"),
    ("ふるいたて よこはまのだいこくばしらよ", "ふるいたて よこはまのだいこくばしらよ"),
    ("よこはまのそらたかく", "よこはまのそらたかく"),
    ("よこはまにかがやく たいほう", "よこはまにかがやく たいほう"),
    ("さあふりぬけみやざき きはくあふれるパワーで",
     "さあふりぬけみやざき きはくあふれるパワーで"),                  # 気迫
    ("あおくわくよこはまの", "あおくわくよこはまの"),
    ("とばせはるかかなた", "とばせはるかかなた"),                     # はるか
    ("そらへいくぞ", "そらえいくぞ"),                                 # 対照: 助詞
    ("へやをでる", "へやをでる"),                                     # 対照: 部屋
]


def main():
    ng = 0
    for src, want in CASES:
        got = sheet_song.read_particles(src)
        good = got == want
        if not good:
            ng += 1
        print("%-4s %-40s -> %s%s" % ("OK" if good else "NG", src, got,
                                      "" if good else "（期待 %s）" % want))
    print("RESULT: %s (%d/%d)" % ("PASS" if ng == 0 else "FAIL",
                                  len(CASES) - ng, len(CASES)))
    return 0 if ng == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
